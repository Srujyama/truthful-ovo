async (page) => {
  const checks = [];
  const require = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  await page.getByRole('button', {name:'Load example',exact:true}).click();
  await page.getByRole('button', {name:'Analyze evidence',exact:true}).click();
  const results = page.getByRole('region',{name:'Analysis results'});
  await results.getByText('$1,500.00',{exact:true}).first().waitFor();
  require((await results.innerText()).includes('$900.00'),'Pipeline matches only $900 and leaves $1,500');
  await results.getByRole('button',{name:'Promised credit',exact:true}).first().click();
  require((await results.locator('blockquote').innerText()).includes('USD 2,400'),'Citation opens the exact original promise');
  await results.getByRole('tab',{name:'Claim draft',exact:true}).click();
  const draft = page.getByRole('textbox',{name:'Follow-up draft'});
  const draftText = await draft.inputValue() + '\nPlease retain the original terms.';
  await draft.fill(draftText);
  await results.getByRole('button',{name:'Approve claim',exact:true}).click();
  await results.getByText('Approval recorded',{exact:true}).waitFor();
  const emailDownload = page.waitForEvent('download');
  await results.getByRole('button',{name:'Download draft',exact:true}).click();
  await (await emailDownload).saveAs('output/playwright/approved-claim.eml');
  const packetDownload = page.waitForEvent('download');
  await results.getByRole('button',{name:'Export evidence',exact:true}).click();
  await (await packetDownload).saveAs('output/playwright/evidence-packet.json');
  checks.push('Approved edited draft and evidence packet downloaded');
  await page.reload();
  await page.getByRole('button',{name:/^Saved cases/}).click();
  await page.getByRole('region',{name:'Saved evidence cases'}).getByRole('button',{name:/Pipeline CRM/}).first().click();
  await results.getByRole('tab',{name:'Claim draft',exact:true}).click();
  require(await page.getByRole('textbox',{name:'Follow-up draft'}).inputValue() === draftText,'Reload preserves exact approved draft and audit record');
  await page.getByRole('combobox',{name:'Try an example'}).selectOption('unmatched');
  await page.getByRole('button',{name:'Load example',exact:true}).click();
  await page.getByRole('button',{name:'Analyze evidence',exact:true}).click();
  await results.getByText('$2,400.00',{exact:true}).first().waitFor();
  require((await results.innerText()).includes('$0.00'),'Wrong reference cannot count an equal-sized credit');
  await page.getByRole('combobox',{name:'Try an example'}).selectOption('pipeline');
  await page.getByRole('button',{name:'Load example',exact:true}).click();
  await page.getByRole('tab',{name:/^Invoice credits/}).click();
  const csv = page.getByRole('textbox',{name:'Invoice credit rows'});
  await csv.fill((await csv.inputValue()).replace(',900.00,',',1000.00,'));
  await page.getByRole('button',{name:'Analyze evidence',exact:true}).click();
  await results.getByText('$1,400.00',{exact:true}).first().waitFor();
  require((await results.innerText()).includes('$1,000.00'),'Changed input recalculates $1,000 applied and $1,400 outstanding');
  await page.getByRole('combobox',{name:'Try an example'}).selectOption('conditional');
  await page.getByRole('button',{name:'Load example',exact:true}).click();
  await page.getByRole('button',{name:'Analyze evidence',exact:true}).click();
  await results.getByText('The reply adds a condition.',{exact:true}).waitFor();
  require((await results.innerText()).includes('$900.00'),'New condition keeps original verified credits and adds no savings');
  await page.getByRole('button',{name:'Guided demo',exact:true}).click();
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.getByRole('button',{name:'Trigger outage',exact:true}).last().click();
  await page.getByRole('button',{name:'Review claim',exact:true}).waitFor();
  await page.getByRole('button',{name:'Review claim',exact:true}).click();
  await page.getByRole('button',{name:'Approve claim',exact:true}).click();
  await page.getByRole('button',{name:'Receive reply',exact:true}).click();
  await page.getByText('A new condition. Not a recovered credit.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Keep original terms',exact:true}).click();
  await page.getByRole('button',{name:'Issue credit',exact:true}).click();
  require((await page.getByRole('region',{name:'Commitment totals'}).innerText()).includes('$900'),'Issued credit does not increase savings');
  await page.getByRole('button',{name:'Apply credit',exact:true}).click();
  require((await page.getByRole('region',{name:'Commitment totals'}).innerText()).includes('$2,900'),'Applied credit increases verified savings to $2,900');
  await page.getByRole('button',{name:'View applied credit',exact:true}).click();
  require((await page.getByRole('dialog').innerText()).includes('CM-NC-204'),'Verified credit opens its matching invoice');
  await page.getByRole('button',{name:'Close source evidence',exact:true}).click();
  await page.getByRole('button',{name:'View email case',exact:true}).click();
  require((await page.getByRole('article').innerText()).includes('$1,500'),'Guided story generalizes to partial email concession');
  const errors = await page.evaluate(() => ({width:document.documentElement.scrollWidth,viewport:innerWidth}));
  require(errors.width <= errors.viewport,'Desktop has no horizontal overflow');
  return {passed:checks.length,checks};
}
